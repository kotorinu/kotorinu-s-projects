export function reviseSugiyamaSource(source: string): string {
  let text = source.replace(/\r\n/g, '\n');
  for (const [id, content] of Object.entries(replacements)) {
    const section = new RegExp(`^# ${id}｜[^\\n]*\\n[\\s\\S]*?(?=^# \\d+｜|(?![\\s\\S]))`, 'm');
    if (!section.test(text)) throw new Error(`Missing Sugiyama phase ${id}`);
    text = text.replace(section, content.trim() + '\n\n---\n\n');
  }
  text = text.replace('**Webライターとしての履歴書**', '**履歴書**');
  return text;
}

export const revisedSugiyamaMarkdown = reviseSugiyamaSource(original);
